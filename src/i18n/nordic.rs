#[inline]
fn pick(
    lang: ResolvedLang,
    sv: &'static str,
    da: &'static str,
    no: &'static str,
    fi: &'static str,
) -> Option<&'static str> {
    Some(match lang {
        ResolvedLang::Sv => sv,
        ResolvedLang::Da => da,
        ResolvedLang::No => no,
        ResolvedLang::Fi => fi,
        _ => return None,
    })
}

